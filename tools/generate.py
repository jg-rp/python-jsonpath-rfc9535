"""Generate specialized JSONPath resolver implementations."""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

TEMPLATES = (
    ("_resolver_basic.py", "BasicResolver"),
    ("_resolver_standard.py", "StandardResolver"),
)

CHECKS = {
    "strict": {
        "IS_JSON_OBJECT(obj)": "type(obj) is dict",
        "IS_JSON_ARRAY(obj)": "type(obj) is list",
        "IS_JSON_COMPOSITE(val)": "type(val) in (list, dict)",
    },
    "native": {
        "IS_JSON_OBJECT(obj)": "isinstance(obj, dict)",
        "IS_JSON_ARRAY(obj)": "isinstance(obj, list)",
        "IS_JSON_COMPOSITE(val)": "isinstance(val, (dict, list))",
    },
    "abstract": {
        "IS_JSON_OBJECT(obj)": "isinstance(obj, Mapping)",
        "IS_JSON_ARRAY(obj)": (
            "not isinstance(obj, (str, bytes)) and isinstance(obj, Sequence)"
        ),
        "IS_JSON_COMPOSITE(val)": (
            "not isinstance(val, (str, bytes)) and isinstance(val, (Mapping, Sequence))"
        ),
    },
}


def replace(source: str, checks: dict[str, str]) -> str:
    """Replace macros with their implementations."""

    for placeholder, sub in checks.items():
        if placeholder not in source:
            raise ValueError(f"no occurrences of {placeholder!r} found")

        source = source.replace(placeholder, sub)

    return source


def replace_class(
    source: str,
    original_name: str,
    generated_name: str,
    version: str,
) -> str:
    """Rename the generated class and insert its generated docstring."""
    sub = f"class {original_name}(Resolver_):"

    if sub not in source:
        raise ValueError(f"expected class {original_name!r}")

    description = f"A JSONPath resolver using {version} JSON type checks."

    return source.replace(
        sub, f'class {generated_name}(Resolver_):\n    """{description}"""\n'
    )


def generate(template_name: str, class_name: str, version: str) -> str:
    """Generate one specialized resolver module."""
    template_path = ROOT / "src" / "jsonpath_rfc9535" / template_name

    source = replace(
        template_path.read_text(encoding="utf-8"),
        CHECKS[version],
    )

    source = replace_class(
        source,
        class_name,
        f"{class_name}{version.title()}",
        version,
    )

    header = (
        "# Automatically generated by tools/generate.py.\n"
        "# Do not edit this file by hand.\n"
        "\n"
    )

    return header + source


def format_source(source: str) -> str:
    """Format generated Python source using Ruff."""

    result = subprocess.run(
        ["ruff", "format", "--stdin-filename", "generated.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    )

    return result.stdout


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Generate specialized resolver implementations."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check generated files without writing them.",
    )
    args = parser.parse_args()

    package_dir = ROOT / "src" / "jsonpath_rfc9535"
    stale_files = []

    for template_name, class_name in TEMPLATES:
        template_stem = Path(template_name).stem

        for version in CHECKS:
            output_name = f"{template_stem}_{version}.py"
            output_path = package_dir / output_name

            generated = format_source(generate(template_name, class_name, version))

            if output_path.exists():
                current = output_path.read_text(encoding="utf-8")
            else:
                current = None

            if current == generated:
                continue

            if args.check:
                stale_files.append(output_name)
                print(f"Out of date: {output_name}")
            else:
                output_path.write_text(generated, encoding="utf-8")
                print(f"Generated: {output_name}")

    if stale_files:
        print("\nGenerated files are out of date. Run `hatch run generate`.")
        return 1

    if args.check:
        print("All generated files are up to date.")

    return 0


if __name__ == "__main__":
    sys.exit(main())
